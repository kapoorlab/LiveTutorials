#!/usr/bin/env python3
"""
Combined HPC Usage Plotting Script for CPU and GPU logs.

- CPU logs: Collected via sacct for the specified date range
- GPU logs: Read from monthly CSV files (auto-generated by separate script)

Both CPU and GPU log directories are kept separate.
"""

import subprocess
from datetime import datetime
from dateutil import parser
import pandas as pd
from pathlib import Path
import matplotlib.pyplot as plt
import seaborn as sns

# -----------------------------
# CONFIG
# -----------------------------
CPU_LOG_DIR = './cpu_logs/'
GPU_LOG_DIR = './gpu_job_logs/'
GPU_PLOT_BASE_DIR = './'

CPU_PARTITIONS = ['h100', 'h200', 'b200', 'cpu']


# -----------------------------
# CPU FUNCTIONS
# -----------------------------
def parse_timedelta(time_str):
    """Convert SLURM CPU time (DD-HH:MM:SS or HH:MM:SS) to hours."""
    days_hours = time_str.split('-')
    if len(days_hours) == 1:
        hours_str = days_hours[0].split(':')[0]
        return int(hours_str)
    elif len(days_hours) == 2:
        days_str = days_hours[0]
        hours_str = days_hours[1].split(':')[0]
        return int(days_str) * 24 + int(hours_str)
    else:
        return 0


def collect_cpu_usage(start_date, end_date, partitions):
    """Collect CPU usage records for given date range and partitions."""
    usage_records = []

    for partition in partitions:
        cmd = (
            f"sacct --starttime={start_date} --endtime={end_date} "
            f"--format=User,TotalCPU,Submit,JobID --parsable2 -a "
            f"--partition={partition} --noheader"
        )
        result = subprocess.run(cmd, shell=True, stdout=subprocess.PIPE, text=True)
        lines = result.stdout.strip().split('\n')

        for line in lines:
            parts = line.split('|')
            if len(parts) >= 4:
                username = parts[0].strip()
                time_used = parts[1].strip()
                submit_time = parts[2].strip()
                job_id = parts[3].strip()

                if username and time_used:
                    cpu_hours = parse_timedelta(time_used)

                    try:
                        submit_datetime = parser.parse(submit_time)
                    except Exception:
                        submit_datetime = None

                    usage_records.append({
                        'JobID': job_id,
                        'User': username,
                        'Partition': partition,
                        'CPUHours': cpu_hours,
                        'SubmitTime': submit_datetime,
                        'DateLogged': datetime.now().strftime('%Y-%m-%d')
                    })

    return usage_records


def plot_cpu_usage(df, year_month, save_dir):
    """Generate plots for CPU usage by partition and user."""
    plot_dir = Path(save_dir) / 'plots'
    plot_dir.mkdir(parents=True, exist_ok=True)

    sns.set(style="whitegrid")

    # Plot per partition
    partition_usage = df.groupby('Partition')['CPUHours'].sum().reset_index()
    partition_usage = partition_usage.sort_values('CPUHours', ascending=False)

    plt.figure(figsize=(10, 6))
    sns.barplot(data=partition_usage, x='Partition', y='CPUHours', hue='Partition', palette='Set2', legend=False)
    plt.ylabel('CPU Hours')
    plt.xlabel('Partition')
    plt.title(f'CPU Usage per Partition for {year_month}')
    plt.xticks(rotation=45)
    plt.tight_layout()
    plt.savefig(plot_dir / f'cpu_usage_per_partition_{year_month}.png', dpi=300)
    plt.close()

    # Plot per user within each partition
    for partition in df['Partition'].dropna().unique():
        partition_df = df[df['Partition'] == partition]
        user_partition_usage = partition_df.groupby('User')['CPUHours'].sum().reset_index()
        user_partition_usage = user_partition_usage.sort_values('CPUHours', ascending=False)

        plt.figure(figsize=(12, 6))
        sns.barplot(data=user_partition_usage, x='User', y='CPUHours', hue='User', palette='coolwarm', legend=False)
        plt.ylabel('CPU Hours')
        plt.xlabel('User')
        plt.title(f'CPU Usage per User in {partition} for {year_month}')
        plt.xticks(rotation=45)
        plt.tight_layout()
        plt.savefig(plot_dir / f'cpu_usage_per_user_{partition}_{year_month}.png', dpi=300)
        plt.close()


def process_cpu_logs(start_date, end_date, year_month):
    """Process and plot CPU logs."""
    print(f"\n{'='*60}")
    print("Processing CPU Logs")
    print(f"{'='*60}")

    save_dir = CPU_LOG_DIR
    Path(save_dir).mkdir(parents=True, exist_ok=True)

    print(f"Collecting CPU usage from {start_date} to {end_date}")
    records = collect_cpu_usage(start_date, end_date, CPU_PARTITIONS)

    if records:
        df = pd.DataFrame(records)

        monthly_log_file = Path(save_dir) / f'cpu_usage_log_{year_month}.csv'
        file_exists = monthly_log_file.exists()
        df.to_csv(monthly_log_file, mode='a', index=False, header=not file_exists)
        print(f"Logged {len(df)} CPU usage records to {monthly_log_file}")

        plot_cpu_usage(df, year_month, save_dir)
        print(f"Generated CPU plots in {save_dir}/plots/")
    else:
        print("No CPU usage records found.")


# -----------------------------
# GPU FUNCTIONS
# -----------------------------
def process_gpu_logs(year_month):
    """Process and plot GPU logs from monthly CSV."""
    print(f"\n{'='*60}")
    print("Processing GPU Logs")
    print(f"{'='*60}")

    # Construct paths based on year_month
    log_csv = Path(GPU_LOG_DIR) / f'gpu_usage_log_{year_month}.csv'

    # Parse year and month for save directory naming
    year, month = year_month.split('-')
    month_name = datetime.strptime(month, '%m').strftime('%b').lower()
    save_dir = Path(GPU_PLOT_BASE_DIR) / f'gpu_usage_{month_name}_{year}'
    save_dir.mkdir(parents=True, exist_ok=True)

    if not log_csv.exists():
        print(f"GPU log file not found: {log_csv}")
        return

    print(f"Reading GPU logs from {log_csv}")
    print(f"Saving plots to {save_dir}")

    # Load data
    df = pd.read_csv(log_csv, parse_dates=['StartTime', 'EndTime', 'DateLogged'])

    # Handle requeues as separate job instances
    df = df.sort_values(['JobID', 'DateLogged'])

    # For each JobID, check if it appears on consecutive days
    df['DaysSincePrev'] = df.groupby('JobID')['DateLogged'].diff().dt.days

    # If a job was seen yesterday (1 day gap) and has 48 hour duration, cap it at 24 hours
    df['AdjustedDurationHours'] = df['DurationHours']
    mask = (df['DaysSincePrev'] == 1) & (df['DurationHours'] >= 48)
    df.loc[mask, 'AdjustedDurationHours'] = 24

    # Recalculate GPU hours with adjusted duration
    df['GPUHours'] = df['GPU_Count'] * df['AdjustedDurationHours']

    # For each JobID, compute time gap to previous run
    df['TimeSincePrev'] = df.groupby('JobID')['StartTime'].diff()

    # A requeue is defined as > 48 hours gap
    df['IsRequeue'] = df['TimeSincePrev'] > pd.Timedelta(hours=48)

    # Create a unique "job instance" counter per JobID
    df['JobInstanceID'] = df.groupby('JobID')['IsRequeue'].cumsum()

    # Combine JobID + instance to form a unique identifier
    df['UniqueJob'] = df['JobID'].astype(str) + "_inst" + df['JobInstanceID'].astype(str)

    # Drop duplicates using UniqueJob
    df = df.drop_duplicates(subset='UniqueJob', keep='first')

    # Create YYYY-MM date label
    df['YearMonth'] = df['StartTime'].dt.to_period('M').astype(str)

    # Get all unique partitions
    all_partitions = df['Partition'].dropna().unique()
    print(f"Found {len(all_partitions)} partitions: {', '.join(all_partitions)}")

    sns.set(style="whitegrid")

    # Loop through each month in the data
    months = df['YearMonth'].sort_values().unique()

    for month in months:
        month_df = df[df['YearMonth'] == month]

        # GPU usage per partition
        partition_usage = month_df.groupby('Partition')['GPUHours'].sum().reset_index()
        partition_usage = partition_usage.sort_values('GPUHours', ascending=False)

        plt.figure(figsize=(10, 6))
        sns.barplot(data=partition_usage, x='Partition', y='GPUHours', hue='Partition', palette='Set2', legend=False)
        plt.ylabel('GPU Hours')
        plt.xlabel('Partition')
        plt.title(f'GPU Usage per Partition for {month}')
        plt.xticks(rotation=45)
        plt.tight_layout()
        plt.savefig(save_dir / f'gpu_usage_per_partition_{month}.png', dpi=300)
        plt.close()

        # Usage per user within each partition
        for partition in month_df['Partition'].dropna().unique():
            partition_df = month_df[month_df['Partition'] == partition]
            user_partition_usage = partition_df.groupby('User')['GPUHours'].sum().reset_index()
            user_partition_usage = user_partition_usage.sort_values('GPUHours', ascending=False)

            plt.figure(figsize=(12, 6))
            sns.barplot(data=user_partition_usage, x='User', y='GPUHours', hue='User', palette='coolwarm', legend=False)
            plt.ylabel('GPU Hours')
            plt.xlabel('User')
            plt.title(f'GPU Usage per User in {partition} for {month}')
            plt.xticks(rotation=45)
            plt.tight_layout()
            plt.savefig(save_dir / f'gpu_usage_per_user_{partition}_{month}.png', dpi=300)
            plt.close()

    print(f"Generated GPU plots in {save_dir}")


# -----------------------------
# MAIN
# -----------------------------
def main(start_date=None, end_date=None):
    """Plot CPU + GPU usage.

    Dates default to the current month; pass them as arguments (or call
    main('2026-11-01', '2026-11-30')) to plot another window. No
    interactive prompt — this runs unattended in notebooks and cron.
    """
    print("="*60)
    print("HPC Usage Plotting Script (CPU + GPU)")
    print("="*60)

    now = datetime.now()

    start_date = start_date or now.replace(day=1).strftime('%Y-%m-%d')
    end_date = end_date or now.strftime('%Y-%m-%d')

    # Extract year-month from start date
    year_month = datetime.strptime(start_date, '%Y-%m-%d').strftime('%Y-%m')

    print(f"\nDate range: {start_date} to {end_date}")
    print(f"Year-Month: {year_month}")

    # Process CPU logs
    process_cpu_logs(start_date, end_date, year_month)

    # Process GPU logs
    process_gpu_logs(year_month)

    print(f"\n{'='*60}")
    print("Done!")
    print(f"{'='*60}")


if __name__ == "__main__":
    main()
